// One command to make the committed Prisma client self-contained:
//   1. Writes apps/api/src/generated/prisma/query_compiler_bg.b64.js (base64 of the Wasm query compiler)
//   2. Patches index.js to load the bytes from that module instead of fs.readFileSync(disk)
// Needed because serverless function bundles (Vercel services) ship only the JS module graph,
// not extra files read from disk at runtime — every dynamic Wasm read crashes with ENOENT.
// Idempotent: run it after every `prisma generate` (the api buildCommand does).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const prismaDir = join(root, 'apps', 'api', 'src', 'generated', 'prisma');
const wasmPath = join(prismaDir, 'query_compiler_bg.wasm');
const b64Path = join(prismaDir, 'query_compiler_bg.b64.js');
const indexPath = join(prismaDir, 'index.js');

const FS_BLOCK = `        const queryCompilerWasmFilePath = require('path').join(config.dirname, 'query_compiler_bg.wasm')
        const queryCompilerWasmFileBytes = require('fs').readFileSync(queryCompilerWasmFilePath)`;
const REPLACEMENT = `        // [patched by scripts/inline-wasm.mjs] inline base64 so the serverless bundle needs no wasm file on disk
        const queryCompilerWasmFileBytes = Buffer.from(require('./query_compiler_bg.b64.js'), 'base64')`;

if (!existsSync(wasmPath)) {
  console.error('query_compiler_bg.wasm not found — run `npx prisma generate` first');
  process.exit(1);
}
if (!existsSync(indexPath)) {
  console.error('prisma index.js not found');
  process.exit(1);
}

const b64 = readFileSync(wasmPath).toString('base64');
writeFileSync(
  b64Path,
  `// Generated by scripts/inline-wasm.mjs — base64 of query_compiler_bg.wasm (${readFileSync(wasmPath).length} bytes -> ${b64.length} chars). Do not edit.\nmodule.exports = "${b64}"\n`,
);

const source = readFileSync(indexPath, 'utf8');
if (source.includes(REPLACEMENT)) {
  console.log('patch already applied');
} else if (source.includes(FS_BLOCK)) {
  writeFileSync(indexPath, source.replace(FS_BLOCK, REPLACEMENT));
  console.log('patched index.js to load the compiler wasm from base64');
} else {
  console.error('unrecognized index.js contents — refusing to patch (prisma version drift?)');
  process.exit(1);
}
console.log('done: query compiler is now bundled in the JS module graph');
